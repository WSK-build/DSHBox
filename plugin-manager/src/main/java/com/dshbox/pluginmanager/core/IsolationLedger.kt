package com.dshbox.pluginmanager.core

/**
 * 市场启停与安全模式隔离清单之间的同步点。
 *
 * 两侧原本各记一份状态：层文件（真正的载体，守卫和市场都写）与安全模式的隔离清单
 * （我们"跳过过哪些插件"的记录）。市场里点启用/停用只改层，于是两边会打架：
 * 市场停用了坏插件，隔离清单里那条记录还在（重复显示）；市场启用了坏插件，
 * 记录仍在，守卫的"清单↔层对齐"下次启动又会把它翻回停用——用户的操作被悄悄撤销。
 *
 * 因此**用户在市场里亲手改过状态的条目，就不再算"被我们隔离"**：市场写层的同时
 * 来这里把它从清单里划掉。层的 `disabled` 行是唯一真相，清单只是"我们干过什么"的凭据。
 *
 * 放在 core 是为了不让市场反向依赖 safety：两边都只依赖这个接口，工厂负责装配。
 */
fun interface IsolationLedger {

    /**
     * 忘掉这些条目 id 的隔离记录（用户已经接管它们的状态）。
     *
     * @param ids 市场刚刚写过层的条目 id（**不是**包名，见 `PackageRowIds`）
     */
    fun forget(ids: Collection<String>)
}
